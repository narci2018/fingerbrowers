def dpapi_decrypt(cipher_bytes: bytes) -> str:
    """Windows 下使用系统 DPAPI (CryptUnprotectData) 解密 Chromium 本地持久化 Cookie"""
    if sys.platform != "win32" or not cipher_bytes:
        return ""
    try:
        import ctypes
        from ctypes import wintypes

        class DATA_BLOB(ctypes.Structure):
            _fields_ = [
                ("cbData", wintypes.DWORD),
                ("pbData", ctypes.POINTER(ctypes.c_byte))
            ]

        # 剥离 Chromium v10 / v11 前缀 (如果存在，前 3 个字节为 b'v10' 或 b'v11')
        raw_payload = cipher_bytes
        if cipher_bytes.startswith(b"v10") or cipher_bytes.startswith(b"v11"):
            raw_payload = cipher_bytes[3:]

        in_blob = DATA_BLOB()
        in_blob.cbData = len(raw_payload)
        in_blob.pbData = ctypes.cast(ctypes.create_string_buffer(raw_payload, len(raw_payload)), ctypes.POINTER(ctypes.c_byte))

        out_blob = DATA_BLOB()

        crypt32 = ctypes.windll.crypt32
        ret = crypt32.CryptUnprotectData(
            ctypes.byref(in_blob),
            None,
            None,
            None,
            None,
            0,
            ctypes.byref(out_blob)
        )
        if ret:
            res_bytes = ctypes.string_at(out_blob.pbData, out_blob.cbData)
            kernel32 = ctypes.windll.kernel32
            kernel32.LocalFree(out_blob.pbData)
            return res_bytes.decode("utf-8", errors="replace")
    except Exception as e:
        logger.debug(f"DPAPI decrypt failed: {e}")
    return ""


class CookieManager:
    """
    生产级 Cookie 导入/导出与跨平台迁移管理器
    1. 支持 Netscape 格式导入导出
    2. 支持 JSON (Cookie-Editor / EditThisCookie 标准格式) 导入导出
    3. 支持在线实例实时注入 / 提取 (CDP Network.getCookies / Network.setCookies)
    4. 支持离线环境从 Chromium SQLite 数据库深度恢复与解密
    5. 具备离线待注入队列 (pending_cookies.json)，保障下次启动 100% 自动装载
    """

    @staticmethod
    def parse_netscape(text: str) -> List[Dict[str, Any]]:
        """解析标准 Netscape 文本格式 Cookie"""
        cookies = []
        for line in text.splitlines():
            line = line.strip()
            if not line:
                continue
            is_httponly = False
            if line.startswith("#HttpOnly_"):
                is_httponly = True
                line = line[len("#HttpOnly_"):]
            elif line.startswith("#"):
                continue

            parts = line.split("\t")
            if len(parts) >= 7:
                domain = parts[0]
                # parts[1] is tailmatch flag (TRUE/FALSE)
                path = parts[2]
                secure = parts[3].upper() == "TRUE"
                try:
                    expires = int(parts[4])
                except Exception:
                    expires = int(time.time() + 365 * 86400)
                name = parts[5]
                value = parts[6]
                cookies.append({
                    "name": name,
                    "value": value,
                    "domain": domain,
                    "path": path,
                    "expires": expires,
                    "expirationDate": expires,
                    "httpOnly": is_httponly,
                    "secure": secure,
                    "sameSite": "Lax"
                })
        return cookies

    @staticmethod
    def export_netscape(cookies: List[Dict[str, Any]]) -> str:
        """导出为标准 Netscape 格式文本"""
        lines = [
            "# Netscape HTTP Cookie File",
            "# https://curl.se/docs/http-cookies.html",
            "# This file was generated by Phantom Browser Engine",
            ""
        ]
        for c in cookies:
            domain = c.get("domain", "")
            flag = "TRUE" if domain.startswith(".") else "FALSE"
            path = c.get("path", "/")
            secure = "TRUE" if c.get("secure", False) else "FALSE"
            exp = c.get("expires") or c.get("expirationDate") or int(time.time() + 365 * 86400)
            try:
                exp_int = int(exp)
            except Exception:
                exp_int = int(time.time() + 365 * 86400)
            name = c.get("name", "")
            val = c.get("value", "")
            prefix = "#HttpOnly_" if c.get("httpOnly", False) else ""
            lines.append(f"{prefix}{domain}\t{flag}\t{path}\t{secure}\t{exp_int}\t{name}\t{val}")
        return "\n".join(lines)

    @staticmethod
    def parse_json(json_str: str) -> List[Dict[str, Any]]:
        """解析 JSON 格式 Cookie 数组"""
        data = json.loads(json_str)
        if isinstance(data, dict):
            # 有时被包装在 {"cookies": [...]} 中
            data = data.get("cookies", [data])
        if not isinstance(data, list):
            raise ValueError("Cookie JSON 必须是对象列表或包含 cookies 键的对象")

        standardized = []
        for item in data:
            if not isinstance(item, dict):
                continue
            name = item.get("name")
            value = item.get("value", "")
            domain = item.get("domain", "")
            if not name:
                continue

            exp = item.get("expirationDate") or item.get("expires") or int(time.time() + 365 * 86400)
            try:
                exp_int = int(exp)
            except Exception:
                exp_int = int(time.time() + 365 * 86400)

            standardized.append({
                "name": str(name),
                "value": str(value),
                "domain": str(domain),
                "path": str(item.get("path", "/")),
                "expires": exp_int,
                "expirationDate": exp_int,
                "httpOnly": bool(item.get("httpOnly", False)),
                "secure": bool(item.get("secure", False)),
                "sameSite": item.get("sameSite", "Lax")
            })
        return standardized

    @classmethod
    def parse_any(cls, content: str) -> List[Dict[str, Any]]:
        """自动推断格式并解析为通用 Cookie 列表"""
        content_stripped = content.strip()
        if content_stripped.startswith("[") or content_stripped.startswith("{"):
            try:
                return cls.parse_json(content_stripped)
            except Exception:
                pass
        return cls.parse_netscape(content_stripped)

    @classmethod
    def load_offline_cookies(cls, user_data_path: Path) -> List[Dict[str, Any]]:
        """
        从 Chromium 本地数据目录的 SQLite (Default/Network/Cookies) 中提取并解密 Cookie
        """
        cookies_db = user_data_path / "Default" / "Network" / "Cookies"
        if not cookies_db.exists():
            # 兼容老版 Chromium 路径 Default/Cookies
            cookies_db = user_data_path / "Default" / "Cookies"
            if not cookies_db.exists():
                return []

        # 为防锁库，拷贝至临时文件只读查询
        temp_db = user_data_path / f"temp_cookies_{int(time.time()*1000)}.db"
        try:
            shutil.copy2(cookies_db, temp_db)
            conn = sqlite3.connect(str(temp_db))
            cursor = conn.cursor()
            cursor.execute(
                "SELECT host_key, name, value, encrypted_value, path, expires_utc, is_secure, is_httponly, samesite FROM cookies"
            )
            rows = cursor.fetchall()
            conn.close()

            results = []
            for row in rows:
                host_key, name, val, encrypted_val, path, expires_utc, is_secure, is_httponly, samesite = row
                
                # 若明文为空，尝试 DPAPI 解密
                real_val = val
                if not real_val and encrypted_val:
                    decrypted = dpapi_decrypt(encrypted_val)
                    if decrypted:
                        real_val = decrypted

                # WebKit / Chromium 时间戳转 UNIX 时间戳
                # Chromium expires_utc 是微秒数，自 1601-01-01 起算
                unix_exp = int(time.time() + 365 * 86400)
                if expires_utc and expires_utc > 0:
                    try:
                        unix_exp = int((expires_utc / 1000000) - 11644473600)
                    except Exception:
                        pass

                results.append({
                    "name": name,
                    "value": real_val or "",
                    "domain": host_key,
                    "path": path or "/",
                    "expires": unix_exp,
                    "expirationDate": unix_exp,
                    "httpOnly": bool(is_httponly),
                    "secure": bool(is_secure),
                    "sameSite": "Lax" if samesite == 1 else ("Strict" if samesite == 2 else "None")
                })
            return results
        except Exception as e:
            logger.debug(f"Failed to read offline cookies: {e}")
            return []
        finally:
            if temp_db.exists():
                try:
                    temp_db.unlink()
                except Exception:
                    pass

    @classmethod
    def get_pending_cookies(cls, user_data_path: Path) -> List[Dict[str, Any]]:
        """获取等待注入的离线 Cookie 队列"""
        pending_file = user_data_path / "pending_cookies.json"
        if pending_file.exists():
            try:
                with open(pending_file, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception:
                pass
        return []

    @classmethod
    def save_pending_cookies(cls, user_data_path: Path, cookies: List[Dict[str, Any]], merge: bool = True):
        """保存离线 Cookie 待注入队列"""
        pending_file = user_data_path / "pending_cookies.json"
        existing = cls.get_pending_cookies(user_data_path) if merge else []
        
        # 以 (name, domain, path) 为键去重
        cookie_map = {}
        for c in existing:
            key = (c.get("name"), c.get("domain"), c.get("path"))
            cookie_map[key] = c
        for c in cookies:
            key = (c.get("name"), c.get("domain"), c.get("path"))
            cookie_map[key] = c

        with open(pending_file, "w", encoding="utf-8") as f:
            json.dump(list(cookie_map.values()), f, ensure_ascii=False, indent=2)

    @classmethod
    def clear_pending_cookies(cls, user_data_path: Path):
        """清空待注入队列"""
        pending_file = user_data_path / "pending_cookies.json"
        if pending_file.exists():
            try:
                pending_file.unlink()
            except Exception:
                pass

    @classmethod
    async def get_live_cookies_via_cdp(cls, ws_endpoint: str) -> List[Dict[str, Any]]:
        """当环境在运行时，通过 CDP WebSocket 实时提取浏览器全部 Cookie（含 Session Cookie）"""
        import websockets
        try:
            async with websockets.connect(ws_endpoint, max_size=10*1024*1024) as ws:
                msg = {"id": 8801, "method": "Storage.getCookies"}
                await ws.send(json.dumps(msg))
                for _ in range(15):
                    raw = await ws.recv()
                    data = json.loads(raw)
                    if data.get("id") == 8801:
                        cookies = data.get("result", {}).get("cookies", [])
                        return [
                            {
                                "name": c.get("name"),
                                "value": c.get("value", ""),
                                "domain": c.get("domain", ""),
                                "path": c.get("path", "/"),
                                "expires": int(c.get("expires", 0)),
                                "expirationDate": int(c.get("expires", 0)),
                                "httpOnly": bool(c.get("httpOnly", False)),
                                "secure": bool(c.get("secure", False)),
                                "sameSite": c.get("sameSite", "Lax")
                            }
                            for c in cookies
                        ]
        except Exception as e:
            logger.debug(f"Failed to get live cookies via CDP: {e}")
        return []

    @classmethod
    async def set_live_cookies_via_cdp(cls, ws_endpoint: str, cookies: List[Dict[str, Any]]) -> bool:
        """当环境在运行时，通过 CDP WebSocket 实时将 Cookie 注入到活跃浏览器中"""
        import websockets
        try:
            cdp_cookies = []
            for c in cookies:
                item = {
                    "name": c.get("name"),
                    "value": c.get("value", ""),
                    "domain": c.get("domain", ""),
                    "path": c.get("path", "/"),
                    "secure": bool(c.get("secure", False)),
                    "httpOnly": bool(c.get("httpOnly", False)),
                }
                exp = c.get("expires") or c.get("expirationDate")
                if exp:
                    item["expires"] = float(exp)
                if c.get("sameSite"):
                    item["sameSite"] = c["sameSite"]
                cdp_cookies.append(item)

            async with websockets.connect(ws_endpoint, max_size=10*1024*1024) as ws:
                msg = {"id": 8802, "method": "Network.setCookies", "params": {"cookies": cdp_cookies}}
                await ws.send(json.dumps(msg))
                raw = await ws.recv()
                return True
        except Exception as e:
            logger.debug(f"Failed to set live cookies via CDP: {e}")
            return False

